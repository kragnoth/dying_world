#!/usr/bin/env python3
"""
coherence_audit.py - pass 9-7: compare ALL our structures against each other. Reads the built dist/kubejs_data.zip (what the game loads).
Writes docs/coherence_audit.md. Checks: sets (placement, salt clashes, exclusion targets, members exist), structures (in a set? start pool exists?
terrain adaptation, spawn overrides, size/radius), biome coverage per structure + biomes with no settlement at all, loot tables referenced
by our NBT chests/barrels exist, dead files in our namespace, third-party namespaces still referenced.
"""
import gzip, json, re, sys, zipfile
from collections import defaultdict, Counter
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import nbtrw

Z = zipfile.ZipFile(ROOT / "dist/kubejs_data.zip"); names = set(Z.namelist())
REF = zipfile.ZipFile(ROOT / "reference/worldgen_reference.zip"); refn = set(REF.namelist())
LOOTREF = zipfile.ZipFile(ROOT / "reference/loot_and_recipes.zip"); lootn = set(LOOTREF.namelist())
def J(n): return json.loads(re.sub(rb"//[^\n]*", b"", Z.read(n) if n in names else REF.read(n)))
def has(kind, rid, ext=".json"):
    ns, p = rid.split(":", 1); n = f"data/{ns}/{kind}/{p}{ext}"
    return n in names or n in refn

def biomes_of(tag, seen=None):
    """resolve a biome tag to biome ids (data zip first, then reference). optional entries counted."""
    seen = seen or set()
    if not tag.startswith("#"): return {tag}
    t = tag[1:]
    if t in seen: return set()
    seen.add(t); ns, p = t.split(":", 1); n = f"data/{ns}/tags/worldgen/biome/{p}.json"
    vals = []
    for src, nm in ((Z, names), (REF, refn)):
        if n in nm:
            j = json.loads(re.sub(rb"//[^\n]*", b"", src.read(n))); vals += j.get("values", [])
            if j.get("replace"): break
    out = set()
    for v in vals:
        v = v["id"] if isinstance(v, dict) else v
        out |= biomes_of(v, seen) if v.startswith("#") else {v}
    return out

L = ["# Coherence audit (pass 9-7) - generated by tools/coherence_audit.py from dist/kubejs_data.zip", ""]
issues = []
# ---------- sets ----------
sets = {n: J(n) for n in names if "/worldgen/structure_set/" in n and n.startswith("data/dying_world/")}
salts = Counter(); members = {}
L += ["## Structure sets (ours)", "", "| set | spacing/sep | freq | exclusion | members |", "|---|---|---|---|---|"]
for n, j in sorted(sets.items()):
    sid = "dying_world:" + n.split("structure_set/")[1][:-5]; pl = j.get("placement", {})
    salts[pl.get("salt")] += 1
    ex = pl.get("exclusion_zone")
    if ex and not any(k == f"data/{ex['other_set'].split(':')[0]}/worldgen/structure_set/{ex['other_set'].split(':')[1]}.json" for k in names | refn):
        issues.append(f"set {sid}: exclusion_zone points to missing set {ex['other_set']}")
    for e in j.get("structures", []):
        members[e["structure"]] = sid
        if not has("worldgen/structure", e["structure"]): issues.append(f"set {sid}: member {e['structure']} has no structure file")
    L.append(f"| {sid} | {pl.get('spacing')}/{pl.get('separation')} | {pl.get('frequency', 1)} | {(ex or {}).get('other_set', '-')}:{(ex or {}).get('chunk_count', '')} | {len(j.get('structures', []))} |")
for s, c in salts.items():
    if c > 1: issues.append(f"salt {s} used by {c} sets (identical placement grids)")
# ---------- structures ----------
L += ["", "## Structures (ours)", "", "| structure | set | biomes | adapt | size/radius | monster spawns | start pool ok |", "|---|---|---|---|---|---|---|"]
cover = defaultdict(set)
for n in sorted(x for x in names if x.startswith("data/dying_world/worldgen/structure/")):
    sid = "dying_world:" + n.split("worldgen/structure/")[1][:-5]; j = J(n)
    b = biomes_of(j["biomes"]) if isinstance(j["biomes"], str) else set(j["biomes"])
    sp = [s["type"].split(":")[1] for s in j.get("spawn_overrides", {}).get("monster", {}).get("spawns", [])]
    pool = j.get("start_pool") or j.get("structure", "")
    ok = has("worldgen/template_pool", pool) if j.get("type") == "minecraft:jigsaw" else "type " + j.get("type", "?")
    L.append(f"| {sid} | {members.get(sid, '**NONE**')} | {len(b)} | {j.get('terrain_adaptation', '-')} | {j.get('size', '-')}/{j.get('max_distance_from_center', '-')} | {','.join(sp) or '-'} | {ok} |")
    if sid not in members: issues.append(f"structure {sid} is in no set (never generates)")
    if ok is False: issues.append(f"structure {sid}: start pool {pool} missing")
    if not b: issues.append(f"structure {sid}: biome tag resolves to 0 biomes")
    kind = re.sub(r"_(plains|taiga|snowy|desert|savanna|swamp|temperate|cold|arid|wild|raiders|abandoned|any)$", "", sid.split(":")[1])
    for bio in b: cover[bio].add(kind)
# ---------- biome coverage ----------
land = {b for b in cover if not any(k in b for k in ("ocean", "river", "beach", "nether", "end", "void", "deep_dark", "lush_caves", "dripstone"))}
SETTLE = ("village_", "abandoned_village", "abandoned_hamlet")
nosettle = sorted(b for b in land if not any(any(k.startswith(s) for s in SETTLE) for k in cover[b]))
L += ["", f"## Biome coverage: {len(cover)} biomes reach at least one structure", "", f"Land biomes without ANY survivor or abandoned settlement ({len(nosettle)}): {', '.join(nosettle) or '-'}", ""]
fams = defaultdict(set)
for b in land:
    for k in cover[b]:
        if k.startswith(("village_", "abandoned_village")): fams[b].add(k)
multi = sorted(b for b, k in fams.items() if len({x.split("_")[-1] for x in k if x.startswith("village_")}) > 1)
L.append(f"Biomes in MORE than one survivor-village family (overlap): {', '.join(multi) or '-'}")
# ---------- loot ----------
missing_loot = Counter(); dead = set()
used_struct_files = set()
for n in names:
    if n.endswith(".nbt") and "/structure/" in n:
        raw = gzip.decompress(Z.read(n))
        for m in re.finditer(rb"LootTable..([a-z0-9_]+:[a-z0-9_/]+)", raw):
            lt = m.group(1).decode(); ns, p = lt.split(":", 1)
            if f"data/{ns}/loot_table/{p}.json" not in names and f"data/{ns}/loot_table/{p}.json" not in lootn: missing_loot[lt] += 1
for lt, c in missing_loot.items(): issues.append(f"loot table {lt} referenced by {c} chest/barrel blocks but not found")
# ---------- third-party ----------
tp = Counter()
for n in names:
    if n.startswith("data/dying_world/") and n.endswith(".json"):
        for m in re.finditer(r'"([a-z_]+):', Z.read(n).decode()):
            if m.group(1) not in ("minecraft", "dying_world", "c", "neoforge", "rustandrebar", "tarbound", "create", "gearwrights", "immersivepetroleum"): tp[m.group(1)] += 1
L += ["", "## Other namespaces referenced from our JSON (biome ids, blocks, types)", "", ", ".join(f"{k} {v}" for k, v in tp.most_common()) or "-"]
L += ["", f"## Issues ({len(issues)})", ""] + [f"- {i}" for i in issues]
(ROOT / "docs/coherence_audit.md").write_text("\n".join(L) + "\n")
print(f"{len(issues)} issues; land biomes without settlements: {len(nosettle)}; overlapping village biomes: {len(multi)}")
for i in issues[:40]: print(" -", i)
print("no-settlement biomes:", nosettle[:40])
