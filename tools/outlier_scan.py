#!/usr/bin/env python3
"""outlier_scan.py - pass 7-0c: scans every distinct house in our village pools (base kubejs sets + accepted donors) and flags palette outliers per family.
Writes docs/building_outliers.md. Read-only (no game files changed). Usage: python3 tools/outlier_scan.py"""
import json, gzip, io, re, zipfile, statistics as st, collections
from pathlib import Path
import nbtlib
ROOT = Path(__file__).resolve().parent.parent
Z = zipfile.ZipFile(ROOT / "reference/structures_nbt.zip")
FAM = ["plains", "taiga", "desert", "savanna", "snowy"]
IGN = re.compile(r"air|jigsaw|structure_void|water|lava|grass|dirt|podzol|mycelium|farmland|gravel|^sand$|snow|ice|leaves|vine|flower|poppy|dandelion|fern|bush|wheat|carrot|potato|beet|crop|stem|kelp|lilac|rose|tulip|orchid|bluet|cornflower|peony|sapling|moss|^path|dirt_path|torch|lantern|chain|ladder|sign|bed|chest|barrel|pot|cauldron|table|furnace|smoker|grindstone|lectern|loom|stonecutter|composter|bell|banner|carpet|rail|button|plate|lever|fence|door|trapdoor|bookshelf|glass|iron_bars|campfire|hay|cobweb|rail|head|skull|armor|frame|painting|cake|candle|bamboo$", re.I)
WOODS = "oak spruce birch jungle acacia dark_oak mangrove cherry crimson warped pale_oak".split()
COL = "white orange magenta light_blue yellow lime pink gray light_gray cyan purple blue brown green red black".split()
def cat(n):
    n = n.split(":")[-1]
    if "terracotta" in n: return "terracotta_col" if any(n.startswith(c + "_") for c in COL) else "terracotta"
    if "wool" in n or n.endswith("_carpet"): return "wool"
    if "concrete" in n: return "concrete"
    if "sandstone" in n: return "sandstone"
    if any(k in n for k in ("quartz", "calcite")): return "white_stone"
    if "mud" in n: return "mud"
    if any(k in n for k in ("basalt", "bone_block", "amethyst", "blackstone")): return "piglin"
    if "mushroom" in n: return "mushroom"
    if "deepslate" in n: return "deepslate"
    if "brick" in n and "stone_brick" not in n: return "brick"
    if any(k in n for k in ("stone", "cobble", "andesite", "granite", "diorite", "tuff")): return "stone"
    if any(w in n for w in WOODS) or "bamboo" in n or "planks" in n or n.endswith("_log") or n.endswith("_wood"): return "wood"
    if re.search(r"(planks|_log|_wood|stairs|slab|fence|fence_gate)$", n): return "wood"
    return "other"
def scan(loc):
    ns, _, p = loc.partition(":")
    raw = gzip.decompress(Z.read(f"data/{ns}/structure/{p}.nbt"))
    t = nbtlib.File.parse(io.BytesIO(raw)); pal = [str(s["Name"]) for s in t["palette"]]
    c = collections.Counter(); mod = 0; tot = 0; tex = 0
    for b in t["blocks"]:
        n = pal[int(b["state"])]
        if n.startswith("minecraft:") and IGN.search(n.split(":")[1]): continue
        if not n.startswith("minecraft:") and IGN.search(n.split(":")[1]): continue
        k = cat(n); c[k] += 1; tot += 1
        if not n.startswith("minecraft:"): mod += 1
    return c, tot, mod, list(map(int, t["size"]))
rows = collections.defaultdict(list)
for fam in FAM:
    j = json.load(open(ROOT / f"datapack/data/minecraft/worldgen/template_pool/village/{fam}/houses.json")); seen = set()
    for e in j["elements"]:
        loc = e["element"].get("location")
        if not loc or loc.startswith("dying_world:") or loc in seen: continue
        seen.add(loc)
        try: c, tot, mod, size = scan(loc)
        except Exception as ex: print("skip", loc, ex); continue
        if tot < 40: continue
        rows[fam].append((loc, {k: v / tot for k, v in c.items()}, tot, mod / tot, size))
CATS = ["wood", "stone", "brick", "deepslate", "sandstone", "terracotta", "terracotta_col", "wool", "concrete", "white_stone", "mud", "piglin", "mushroom", "other"]
def grp(loc):
    return "base" if loc.startswith("minecraft:") else loc.split(":")[0] + ":" + loc.split("village/")[1].split("/")[0]
def dist(f, m): return sum(abs(f.get(k, 0) - m[k]) for k in CATS) / 2
def med_of(rs): return {k: st.median(r[1].get(k, 0) for r in rs) for k in CATS}
out = ["# Building outliers (pass 7-0c, generated by tools/outlier_scan.py)\n",
       "Scope: every distinct house in our village pools = the user's kubejs BASE set (`minecraft:village/<family>/houses`) + accepted donor sets. Palette = share of structural blocks (ground, plants, furniture, glass ignored).",
       "Part 1 = whole donor sets that look different from the family base. Part 2 = single houses that stick out inside their own set. 'coloured' = wool + concrete + coloured terracotta.\n"]
p2 = []
for fam in FAM:
    R = rows[fam]; base = [r for r in R if grp(r[0]) == "base"]; bm = med_of(base)
    out.append(f"\n## {fam}")
    groups = collections.defaultdict(list)
    for r in R: groups[grp(r[0])].append(r)
    for g, rs in groups.items():
        m = med_of(rs); top = ", ".join(f"{k} {int(v*100)}%" for k, v in sorted(m.items(), key=lambda kv: -kv[1])[:3] if v > .03)
        col = st.median(r[1].get("terracotta_col", 0) + r[1].get("wool", 0) + r[1].get("concrete", 0) for r in rs)
        md = st.median(dist(r[1], bm) for r in rs)
        out.append(f"- **{g}** ({len(rs)} houses): {top}; coloured {int(col*100)}%; distance from base {md:.2f}" + ("  <- DIFFERENT FROM BASE" if g != "base" and md > .4 else ""))
        for loc, f, tot, mod, size in rs:
            tip = bool(re.search(r"tipi|teepee|tepee|wigwam", loc, re.I)); c = f.get("terracotta_col", 0) + f.get("wool", 0) + f.get("concrete", 0)
            d = dist(f, m)
            if tip or (g == "base" and (c > .15 or dist(f, bm) > .3)) or (g != "base" and d > .3) or size[1] >= 22 or max(size[0], size[2]) >= 22:
                why = [f"{k} +{int((f.get(k,0)-m[k])*100)}%" for k in CATS if f.get(k, 0) - m[k] > .15][:2]
                p2.append((fam, tip, loc, d, c, why, size))
out.append("\n# Part 2 - single houses that stand out (teepees, very colourful, off-palette vs their own set, or >=22 blocks big)\n")
for fam in FAM:
    xs = sorted([x for x in p2 if x[0] == fam], key=lambda x: (-x[1], -x[3]))
    out.append(f"\n## {fam} ({len(xs)})")
    for _, tip, loc, d, c, why, size in xs:
        short = loc.replace("minecraft:village/", "").replace("kaisyn:village/", "k:").replace("windswept:village/", "w:").replace("brutos:village/", "b:")
        out.append(f"- `{short}` {'TEEPEE ' if tip else ''}{'; '.join(why)}{'; ' if why else ''}coloured {int(c*100)}% size={size}")
(ROOT / "docs/building_outliers.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
