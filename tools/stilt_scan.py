#!/usr/bin/env python3
"""stilt_scan.py - pass 7-0d: finds STILT houses (floor raised off the ground on poles) in our village pools + gearwrights abandoned sets.
Heuristic per template: footprint F = size_x*size_z; f[y] = share of F filled by non-air/non-jigsaw blocks in layer y. Stilts if the first 'floor' layer (first layer >=1 with f>=.5, ground blocks ignored)
is at y>=2 while every layer below is sparse (f<.5, median <.25; farms skipped) and contains >=4 pole-like blocks (log/wood/fence/wall/bamboo/pillar/post/stairs-free). Read-only; writes docs/stilt_houses.md."""
import json, gzip, io, re, zipfile, collections, sys
from pathlib import Path
import nbtlib
ROOT = Path(__file__).resolve().parent.parent
Z = zipfile.ZipFile(ROOT / "reference/structures_nbt.zip")
SKIP = re.compile(r"air$|jigsaw|structure_void|^grass_block$|^dirt$|^dirt_path$|^coarse_dirt$|^podzol$|^mycelium$|^farmland$|^sand$|^gravel$|^snow_block$|^grass$|^tall_grass$|^short_grass$")
POLE = re.compile(r"_log|_wood|fence|_wall|bamboo|stem|pillar|post|iron_bars|chain|hyphae|stripped")
def analyse(raw, name=''):
    t = nbtlib.File.parse(io.BytesIO(raw)); sx, sy, sz = map(int, t["size"]); pal = [str(s["Name"]).split(":")[-1] for s in t["palette"]]
    F = max(1, sx * sz); lay = [0] * sy; pole = [0] * sy
    for b in t["blocks"]:
        n = pal[int(b["state"])]
        if SKIP.search(n): continue
        y = int(b["pos"][1]); lay[y] += 1
        if POLE.search(n): pole[y] += 1
    f = [c / F for c in lay]
    fl = next((y for y in range(1, sy) if f[y] >= .5), None)
    st = fl is not None and fl >= 2 and all(f[y] < .5 for y in range(fl)) and sum(pole[:fl]) >= 4 and sorted(f[:fl])[fl // 2] < .25 and 'farm' not in name
    return st, fl, [round(x, 2) for x in f[:6]], [sx, sy, sz]
def grp(loc): return "base" if loc.startswith("minecraft:") else loc.split(":")[0] + ":" + loc.split("village/")[1].split("/")[0]
rows = collections.defaultdict(list)
for fam in ["plains", "taiga", "desert", "savanna", "snowy"]:
    j = json.load(open(ROOT / f"datapack/data/minecraft/worldgen/template_pool/village/{fam}/houses.json")); seen = set()
    for e in j["elements"]:
        loc = e["element"].get("location")
        if not loc or loc.startswith("dying_world:") or loc in seen: continue
        seen.add(loc); ns, _, p = loc.partition(":")
        try: st, fl, f, size = analyse(gzip.decompress(Z.read(f"data/{ns}/structure/{p}.nbt")), p)
        except Exception as ex: continue
        rows[(fam, grp(loc))].append((loc, st, fl, f, size))
out = ["# Stilt houses (pass 7-0d, generated by tools/stilt_scan.py)\n", "Stilt = floor raised >=2 blocks above the template bottom on poles. `floor@y` = first solid floor layer.\n"]
for (fam, g), rs in sorted(rows.items()):
    n = sum(1 for r in rs if r[1]); out.append(f"\n## {fam} / {g}: {n} of {len(rs)} stilt houses")
    for loc, st, fl, f, size in rs:
        if st: out.append(f"- `{loc.split('village/')[-1]}` floor@y{fl} layers {f} size={size}")
# gearwrights abandoned ruins (ruined by design) - count only
ab = collections.defaultdict(lambda: [0, 0, []])
for n in Z.namelist():
    m = re.match(r"data/gearwrights/structure/abandoned/([^/]+)/(houses|[^/]+)/(.+)\.nbt$", n)
    if not m or "burnt" in n: continue
    try: st, fl, f, size = analyse(gzip.decompress(Z.read(n)), n)
    except Exception: continue
    a = ab[m.group(1)]; a[1] += 1
    if st: a[0] += 1; a[2].append(m.group(3))
out.append("\n## gearwrights abandoned ruins/hamlets/villages (per biome: stilt NBTs / total)\n")
for b, (s, t, names) in sorted(ab.items()): out.append(f"- {b}: {s}/{t}" + (f" e.g. {', '.join(names[:5])}" if names else ""))
(ROOT / "docs/stilt_houses.md").write_text("\n".join(out) + "\n"); print("\n".join(out)[:7000])
